let bag: string[] = [];

function pick(): string {
  if (bag.length === 0) {
    bag = messages.slice();
    for (let i = bag.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [bag[i], bag[j]] = [bag[j], bag[i]];
    }
  }
  return bag.pop() as string;
}

export default function (pi: ExtensionAPI) {
  pi.on("turn_start", async (_event, ctx) => {
    const line = pick();
    try {
      ctx.ui.setWorkingMessage(line);
    } catch {
      return;
    }
    // 兜底：万一有人手动把 whimsical 重新打开，它还会在同一次 turn_start 里
    // 写同一个提示位（pi 按包类型排序加载，本地扩展在先，会被盖掉）。
    // 延后一拍再写一次，保证合并后的这份台账是最后落地的那个。
    setTimeout(() => {
      try {
        ctx.ui.setWorkingMessage(line);
      } catch {
        // /new、/fork、会话切换后 ctx 会失效，忽略即可
      }
    }, 0);
  });
  pi.on("turn_end", async (_event, ctx) => {
    try {
      ctx.ui.setWorkingMessage(); // 复位，下一轮再抽
    } catch {
      /* 同上：会话替换后的旧 ctx */
    }
  });
}
